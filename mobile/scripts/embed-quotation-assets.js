#!/usr/bin/env node
/**
 * Embeds the quotation images (and brand logos) into a TypeScript file as
 * base64 text, so they work identically in Expo Go AND in an exported Android /
 * iOS build.  (Reading bundled image files at runtime fails in release builds.)
 *
 * Run from the `mobile` folder, any time you change an image:
 *     node scripts/embed-quotation-assets.js
 *
 * Brand logos are auto-trimmed (empty transparent/white padding removed, so the visible logo is
 * as large as possible) and shrunk to a print-sharp size IF the optional "sharp" package is installed:
 *     npm i -D sharp
 * Without it, logos are embedded as they are.
 *
 * Reads : assets/quotation/{ecdial,daikin}_quotation_{header,terms,bank,footer}.(jpg|png)
 *         assets/brands/{daikin,mitsubishi,lg,general,godrej,bluestar,onida}.(png|jpg)
 * Writes: src/screens/quotationAssetData.ts
 */
const fs = require('fs');
const path = require('path');
let sharp = null;
try { sharp = require('sharp'); } catch (e) { /* optional */ }

const root = process.cwd();
const quoteDir = path.join(root, 'assets', 'quotation');
const brandDir = path.join(root, 'assets', 'brands');
const outFile = path.join(root, 'src', 'screens', 'quotationAssetData.ts');

const find = (dir, base) => {
  for (const ext of ['.jpg', '.jpeg', '.png']) {
    const p = path.join(dir, base + ext);
    if (fs.existsSync(p)) return p;
  }
  return null;
};
const mime = (f) => (/\.png$/i.test(f) ? 'image/png' : 'image/jpeg');
const toUri = (f) => `data:${mime(f)};base64,${fs.readFileSync(f).toString('base64')}`;
const kb = (f) => Math.round(fs.statSync(f).size / 1024);

let warn = 0;
const note = (label, f) => {
  const size = kb(f);
  const flag = size > 150 ? '  <-- large: compress it (every PDF carries it)' : '';
  if (flag) warn++;
  console.log(`  ${label.padEnd(26)} ${String(size).padStart(5)} KB${flag}`);
};

(async () => {
if (!fs.existsSync(quoteDir)) {
  console.error(`Cannot find ${quoteDir}\nRun this from the "mobile" folder.`);
  process.exit(1);
}

let ts = '// AUTO-GENERATED by scripts/embed-quotation-assets.js - do not edit by hand.\n';
ts += '// Re-run:  node scripts/embed-quotation-assets.js\n\n';

console.log('Quotation images');
ts += 'export const QUOTE_IMAGES = {\n';
for (const t of ['ECDIAL', 'DAIKIN']) {
  ts += `  ${t}: {\n`;
  for (const slot of ['header', 'terms', 'bank', 'footer']) {
    const f = find(quoteDir, `${t.toLowerCase()}_quotation_${slot}`);
    if (!f) {
      console.error(`Missing image: assets/quotation/${t.toLowerCase()}_quotation_${slot}.jpg`);
      process.exit(1);
    }
    note(`${t.toLowerCase()} ${slot}`, f);
    ts += `    ${slot}: '${toUri(f)}',\n`;
  }
  ts += '  },\n';
}
ts += '};\n\n';

console.log(sharp ? 'Brand logos (auto-trim + resize via sharp)' : 'Brand logos (install sharp to auto-trim: npm i -D sharp)');
const LOGOS = {
  DAIKIN: 'daikin', MITSUBISHI: 'mitsubishi', LG: 'lg', GENERAL: 'general',
  GODREJ: 'godrej', BLUESTAR: 'bluestar', ONIDA: 'onida',
};
ts += 'export const BRAND_LOGOS: Record<string, string> = {\n';
let logoCount = 0;
for (const [key, base] of Object.entries(LOGOS)) {
  const f = fs.existsSync(brandDir) ? find(brandDir, base) : null;
  if (!f) {
    console.log(`  ${key.padEnd(26)} not found (skipped)`);
    continue;
  }
  if (sharp) {
    try {
      const buf = await sharp(f).trim().resize({ height: 96, withoutEnlargement: true }).png({ compressionLevel: 9 }).toBuffer();
      console.log(`  ${key.padEnd(26)} ${String(Math.round(buf.length / 1024)).padStart(5)} KB   (was ${kb(f)} KB, trimmed)`);
      ts += `  ${key}: 'data:image/png;base64,${buf.toString('base64')}',\n`;
      logoCount++;
      continue;
    } catch (e) {
      console.log(`  ${key}: trim failed (${e.message}), embedding as is`);
    }
  }
  note(key, f);
  ts += `  ${key}: '${toUri(f)}',\n`;
  logoCount++;
}
ts += '};\n';

fs.writeFileSync(outFile, ts);
console.log(`\nWrote ${path.relative(root, outFile)}  (${Math.round(ts.length / 1024)} KB, ${logoCount} logos)`);
if (warn) console.log(`\n${warn} image(s) above are large. Compress them (e.g. tinypng.com) and run this again.`);

})();
